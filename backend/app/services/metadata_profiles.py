def list_metadata_profiles() -> list[dict]:
    return [
        {
            "id": profile["id"],
            "label": profile["label"],
            "description": profile["description"],
            "metabolomics_assay_type": profile["metabolomics_assay_type"],
            "required_field_paths": list(profile["required_field_paths"]),
            "default_payload_json": deepcopy(profile["defaults"]),
        }
        for profile in METADATA_PROFILES
    ]


def get_metadata_profile(profile_id: str | None) -> dict | None:
    for profile in METADATA_PROFILES:
        if profile["id"] == profile_id:
            return profile
    return None
